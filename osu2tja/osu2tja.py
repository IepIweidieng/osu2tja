@dataclass
class OsuEvent:
    event_type: str
    start_time: float
    filename: str = ""
    x_offset: float = 0
    y_offset: float = 0
    end_time: float = 0

def get_event(line: str) -> Optional[OsuEvent]:
    if line is None or line.lstrip().startswith('//'):
        return None

    params = line.split(',', 2)
    if len(params) < 3:
        return None

    event_type, start_time, params = params
    if event_type.isdigit():
        event_type = INT_TO_OSU_EVENT.get(int(event_type), event_type)

    res = OsuEvent(
        event_type = event_type,
        start_time = float(start_time),
    )
    if event_type in {OSU_EVENT_BG, OSU_EVENT_VIDEO}:
        filename, _, params = params.partition(',')
        x_offset, _, params = params.partition(',') # optional
        y_offset, _, params = params.partition(',') # optional
        if filename.startswith('"') and filename.endswith('"'):
            filename = filename[1:-1]
        res.filename = filename
        res.x_offset = float(x_offset or 0)
        res.y_offset = float(y_offset or 0)
    elif event_type == OSU_EVENT_BREAK:
        end_time = float(params.partition(',')[0])
        res.end_time = end_time

    return res


def get_timing_point(str, prev_timing_point: Optional[OsuTimingPoint] = None) -> Optional[OsuTimingPoint]:
    if str is None:
        return None

    # in case new items are added to osu format
    ps = str.split(',')
    if len(ps) < 2:
        return None

    offset, rawbpmv = ps[:2]
    beats = ps[2] if len(ps) > 2 else '4'
    sevol = ps[5] if len(ps) > 5 else '100'
    uninherited = int(ps[6]) if len(ps) > 6 else float(rawbpmv) > 0
    effects = int(ps[7] if len(ps) > 7 else '0')

    # fill a timing point dict
    ret = OsuTimingPoint(
        offset = float(offset),  # time
        offset_raw = float(offset),
        sevol = float(sevol),
        ggt = ((effects & OSU_TMFX_GGT) != 0),
        hidefirst = EHideFirst.TO_UNHIDE if (effects & OSU_TMFX_HIDEFIRST) else EHideFirst.SHOWN,
    )
    if uninherited: # BPM change
        ret.mspb = abs(float(rawbpmv))
        ret.bpm = 60 * 1000.0 / ret.mspb
        ret.beats = abs(int(beats)) # measure change
        ret.scroll = math.copysign(1.0, float(rawbpmv))
        ret.redtm = ret
    else: # SCROLL speed change
        assert prev_timing_point is not None
        merge_with_prev = (
            prev_timing_point.offset == ret.offset
            and prev_timing_point.is_redline())
        if merge_with_prev:
            ret = prev_timing_point
        else:
            ret.mspb = prev_timing_point.mspb
            ret.bpm = prev_timing_point.bpm
            ret.beats = prev_timing_point.beats # ignored for inherited timing points
            ret.redtm = prev_timing_point.redtm
            ret.offset = get_real_offset(ret.offset, raw=True)
        assert ret.redtm is not None
        ret.scroll = -math.copysign(100.0, ret.redtm.scroll) / float(rawbpmv)
        if merge_with_prev:
            if round(ret.offset_raw) in inspect_ms:
                print_with_pended(f"[INSPECT_MS {ret.offset_raw}] merged timing point {ret}", file=sys.stderr)
            return None # merge uninherited (red) + inherited (green) timing points

    if round(ret.offset_raw) in inspect_ms:
        print_with_pended(f"[INSPECT_MS {ret.offset_raw}] new timing point {ret}", file=sys.stderr)
    return ret

