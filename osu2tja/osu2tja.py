def get_section_name(str):
    if str is None:
        return ""
    if str.startswith('[') and str.endswith(']'):
        return str[1:-1]
    return ""


def get_var(str: str) -> Tuple[str, str]:
    if str is None:
        return "", ""
    var_name, _, var_value = str.partition(':')
    return var_name.strip(), var_value.strip()

@dataclass
class OsuEvent:
    event_type: str
    start_time: float
    filename: str = ""
    x_offset: float = 0
    y_offset: float = 0
    end_time: float = 0

def get_event(line: str) -> Optional[OsuEvent]:
    if line is None or line.lstrip().startswith('//'):
        return None

    params = line.split(',', 2)
    if len(params) < 3:
        return None

    event_type, start_time, params = params
    if event_type.isdigit():
        event_type = INT_TO_OSU_EVENT.get(int(event_type), event_type)

    res = OsuEvent(
        event_type = event_type,
        start_time = float(start_time),
    )
    if event_type in {OSU_EVENT_BG, OSU_EVENT_VIDEO}:
        filename, _, params = params.partition(',')
        x_offset, _, params = params.partition(',') # optional
        y_offset, _, params = params.partition(',') # optional
        if filename.startswith('"') and filename.endswith('"'):
            filename = filename[1:-1]
        res.filename = filename
        res.x_offset = float(x_offset or 0)
        res.y_offset = float(y_offset or 0)
    elif event_type == OSU_EVENT_BREAK:
        end_time = float(params.partition(',')[0])
        res.end_time = end_time

    return res


BEAT_RES_MS = 2

def get_beat_res(mspb: float) -> int:
    beat_res = 192 // 4 # start with 1/192nd
    # scale beat_res by power of 2 so that t_unit <= MS_BEAT_RES
    t_unit = mspb / beat_res
    log = int(math.floor(math.log2(t_unit / BEAT_RES_MS)))
    if log > 0:
        beat_res = beat_res << log
    return beat_res

def get_t_unit(tm: OsuTimingPoint) -> float:
    return tm.mspb / tm.beat_res

def get_dt_unit_cnt(t_unit: float, offset0: Union[float, int], offset1: Union[float, int]) -> int:
    delta = (offset1 - offset0) / t_unit
    return int(round(delta))

def get_timing_point(G: "Global", str, prev_timing_point: Optional[OsuTimingPoint] = None) -> Optional[OsuTimingPoint]:
    if str is None:
        return None

    # in case new items are added to osu format
    ps = str.split(',')
    if len(ps) < 2:
        return None

    offset, rawbpmv = ps[:2]
    beats = ps[2] if len(ps) > 2 else '4'
    sevol = ps[5] if len(ps) > 5 else '100'
    uninherited = int(ps[6]) if len(ps) > 6 else float(rawbpmv) > 0
    effects = ETimingFxOsu(int(ps[7] if len(ps) > 7 else '0'))

    # fill a timing point dict
    ret = OsuTimingPoint(
        offset = float(offset),  # time
        offset_raw = float(offset),
        sevol = float(sevol),
        ggt = bool(effects & ETimingFxOsu.GGT),
    )
    if uninherited: # BPM change
        ret.mspb = abs(float(rawbpmv))
        ret.bpm = 60 * 1000.0 / ret.mspb
        ret.beats = abs(int(beats)) # measure change
        ret.beat_res = get_beat_res(ret.mspb)
        ret.scroll = math.copysign(1.0, float(rawbpmv))
        ret.hidefirst = EHideFirst.TO_UNHIDE if (effects & ETimingFxOsu.HIDEFIRST) else EHideFirst.SHOWN
        ret.redtm = ret
    else: # SCROLL speed change
        assert prev_timing_point is not None
        merge_with_prev = (
            prev_timing_point.offset_raw == ret.offset_raw
            and prev_timing_point.is_redline()
            and prev_timing_point.ggt == ret.ggt)
        if merge_with_prev:
            ret = prev_timing_point
        else:
            ret.mspb = prev_timing_point.mspb
            ret.bpm = prev_timing_point.bpm
            ret.beat_res = prev_timing_point.beat_res
            ret.beats = prev_timing_point.beats # ignored for inherited timing points
            ret.hidefirst = prev_timing_point.hidefirst # ignored? (use redtm.hidefirst instead)
            ret.redtm = prev_timing_point.redtm
            ret.offset = get_real_offset(G, ret.offset, raw=True)
        assert ret.redtm is not None
        ret.scroll = -math.copysign(100.0, ret.redtm.scroll) / float(rawbpmv)
        if merge_with_prev:
            if round(ret.offset_raw) in D.inspect_ms:
                print_with_pended(f"// [INSPECT_MS {ret.offset_raw}] merged timing point {ret}", file=sys.stderr)
            return None # merge uninherited (red) + inherited (green) timing points

    if round(ret.offset_raw) in D.inspect_ms:
        print_with_pended(f"// [INSPECT_MS {ret.offset_raw}] new timing point {ret}", file=sys.stderr)
    return ret


